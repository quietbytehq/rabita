//! A small, line-preserving editor for INI-style files such as
//! `/etc/sssd/sssd.conf`.
//!
//! It keeps comments, blank lines and ordering intact, which matters when
//! the file was written by `realmd` and someone later reads the backup.

/// An INI document kept as lines.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IniDocument {
    lines: Vec<String>,
}

fn section_header(line: &str) -> Option<&str> {
    let t = line.trim();
    if t.starts_with('[') && t.ends_with(']') && t.len() >= 2 {
        Some(t[1..t.len() - 1].trim())
    } else {
        None
    }
}

fn key_of(line: &str) -> Option<&str> {
    let t = line.trim_start();
    if t.starts_with('#') || t.starts_with(';') || t.is_empty() {
        return None;
    }
    let (k, _) = t.split_once('=')?;
    Some(k.trim())
}

impl IniDocument {
    /// Parses text. Never fails: unknown lines are kept as-is.
    #[must_use]
    pub fn parse(text: &str) -> Self {
        Self {
            lines: text.lines().map(str::to_owned).collect(),
        }
    }

    /// Renders back to text with a trailing newline.
    #[must_use]
    pub fn render(&self) -> String {
        let mut s = self.lines.join("\n");
        s.push('\n');
        s
    }

    /// Section names in order of appearance.
    #[must_use]
    pub fn sections(&self) -> Vec<String> {
        self.lines
            .iter()
            .filter_map(|l| section_header(l).map(str::to_owned))
            .collect()
    }

    /// Line range `[start, end)` of a section's body (after its header).
    fn section_range(&self, section: &str) -> Option<(usize, usize)> {
        let start = self
            .lines
            .iter()
            .position(|l| section_header(l).is_some_and(|s| s.eq_ignore_ascii_case(section)))?
            + 1;
        let end = self.lines[start..]
            .iter()
            .position(|l| section_header(l).is_some())
            .map_or(self.lines.len(), |i| start + i);
        Some((start, end))
    }

    /// Reads a value.
    #[must_use]
    pub fn get(&self, section: &str, key: &str) -> Option<String> {
        let (start, end) = self.section_range(section)?;
        self.lines[start..end].iter().find_map(|l| {
            if key_of(l).is_some_and(|k| k.eq_ignore_ascii_case(key)) {
                l.split_once('=').map(|(_, v)| v.trim().to_owned())
            } else {
                None
            }
        })
    }

    /// Sets a value, creating the section at the end if needed. Replaces an
    /// existing key in place; otherwise appends to the section body (before
    /// trailing blank lines).
    pub fn set(&mut self, section: &str, key: &str, value: &str) {
        let new_line = format!("{key} = {value}");
        let (start, end) = if let Some(r) = self.section_range(section) {
            r
        } else {
            if !self.lines.is_empty() && !self.lines.last().is_some_and(|l| l.trim().is_empty()) {
                self.lines.push(String::new());
            }
            self.lines.push(format!("[{section}]"));
            let n = self.lines.len();
            (n, n)
        };
        if let Some(i) = self.lines[start..end]
            .iter()
            .position(|l| key_of(l).is_some_and(|k| k.eq_ignore_ascii_case(key)))
        {
            self.lines[start + i] = new_line;
            return;
        }
        let mut insert_at = end;
        while insert_at > start && self.lines[insert_at - 1].trim().is_empty() {
            insert_at -= 1;
        }
        self.lines.insert(insert_at, new_line);
    }

    /// Sets the same key in every section whose name starts with `prefix`
    /// (e.g. `domain/`). Returns how many sections were touched.
    pub fn set_in_sections_with_prefix(&mut self, prefix: &str, key: &str, value: &str) -> usize {
        let targets: Vec<String> = self
            .sections()
            .into_iter()
            .filter(|s| {
                s.to_ascii_lowercase()
                    .starts_with(&prefix.to_ascii_lowercase())
            })
            .collect();
        for s in &targets {
            self.set(s, key, value);
        }
        targets.len()
    }
}

#[cfg(test)]
mod tests {
    use super::IniDocument;

    const SSSD: &str = "\
[sssd]
domains = lab.quietbyte.test
config_file_version = 2
services = nss, pam

[domain/lab.quietbyte.test]
# generated by realmd
default_shell = /bin/bash
krb5_store_password_if_offline = True
cache_credentials = True
realmd_tags = manages-system joined-with-adcli
id_provider = ad
fallback_homedir = /home/%u@%d
ad_domain = lab.quietbyte.test
use_fully_qualified_names = True
ldap_id_mapping = True
access_provider = ad
";

    #[test]
    fn reads_values() {
        let doc = IniDocument::parse(SSSD);
        assert_eq!(
            doc.get("sssd", "domains").as_deref(),
            Some("lab.quietbyte.test")
        );
        assert_eq!(
            doc.get("domain/lab.quietbyte.test", "use_fully_qualified_names")
                .as_deref(),
            Some("True")
        );
        assert_eq!(doc.get("domain/lab.quietbyte.test", "missing"), None);
        assert_eq!(doc.get("nope", "x"), None);
    }

    #[test]
    fn replaces_in_place_and_keeps_comments() {
        let mut doc = IniDocument::parse(SSSD);
        doc.set(
            "domain/lab.quietbyte.test",
            "use_fully_qualified_names",
            "False",
        );
        doc.set("domain/lab.quietbyte.test", "fallback_homedir", "/home/%u");
        let out = doc.render();
        assert!(out.contains("# generated by realmd\n"));
        assert!(out.contains("use_fully_qualified_names = False\n"));
        assert!(out.contains("fallback_homedir = /home/%u\n"));
        assert!(!out.contains("fallback_homedir = /home/%u@%d"));
        assert_eq!(out.matches("use_fully_qualified_names").count(), 1);
    }

    #[test]
    fn appends_new_key_to_section_before_trailing_blank() {
        let mut doc = IniDocument::parse(SSSD);
        doc.set("sssd", "default_domain_suffix", "lab.quietbyte.test");
        let out = doc.render();
        let idx_new = out.find("default_domain_suffix").unwrap();
        let idx_next_section = out.find("[domain/").unwrap();
        assert!(idx_new < idx_next_section);
        assert!(out.contains(
            "services = nss, pam\ndefault_domain_suffix = lab.quietbyte.test\n\n[domain/"
        ));
    }

    #[test]
    fn creates_missing_section() {
        let mut doc = IniDocument::parse("[a]\nx = 1\n");
        doc.set("b", "y", "2");
        assert_eq!(doc.render(), "[a]\nx = 1\n\n[b]\ny = 2\n");
        let mut empty = IniDocument::parse("");
        empty.set("sssd", "k", "v");
        assert_eq!(empty.render(), "[sssd]\nk = v\n");
    }

    #[test]
    fn prefix_set_touches_all_domains() {
        let mut doc = IniDocument::parse("[domain/a]\nx = 1\n[domain/b]\n[other]\n");
        assert_eq!(doc.set_in_sections_with_prefix("domain/", "x", "9"), 2);
        assert_eq!(doc.get("domain/a", "x").as_deref(), Some("9"));
        assert_eq!(doc.get("domain/b", "x").as_deref(), Some("9"));
        assert_eq!(doc.get("other", "x"), None);
    }
}
